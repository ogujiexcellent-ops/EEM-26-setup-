# ── Flat lesson list built from the modules above ───────────────────────────
ALL_LESSONS: list[dict] = []
for mod in MODULES:
    for lesson in mod["lessons"]:
        ALL_LESSONS.append(
            {
                "lesson_number": len(ALL_LESSONS) + 1,
                "module_number": mod["number"],
                "module_title": mod["title"],
                "title": lesson["title"],
                "url": lesson["url"],
            }
        )

TOTAL_LESSONS = len(ALL_LESSONS)  # 37


def get_lesson(lesson_number: int) -> dict | None:
    """Return lesson dict for 1-based lesson_number."""
    if 1 <= lesson_number <= TOTAL_LESSONS:
        return ALL_LESSONS[lesson_number - 1]
    return None


def get_module_lessons(module_number: int) -> list[dict]:
    return [l for l in ALL_LESSONS if l["module_number"] == module_number]
